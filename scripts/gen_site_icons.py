"""Embed site icons + search engine icons as data URIs in a TS module.

Reads assets/site-icons/*, converts bing.ico to PNG, and writes
src/main/site-icon-data.ts (checked in, regenerable, works packaged).
"""
import base64
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "assets", "site-icons")
OUT = os.path.join(REPO, "src", "main", "site-icon-data.ts")

MIME = {".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon"}

entries: dict[str, str] = {}


def add(key: str, data: bytes, ext: str) -> None:
    b64 = base64.b64encode(data).decode("ascii")
    entries[key] = f"data:{MIME[ext]};base64,{b64}"


for fname in sorted(os.listdir(SRC)):
    fpath = os.path.join(SRC, fname)
    if not os.path.isfile(fpath):
        continue
    stem, ext = os.path.splitext(fname)
    ext = ext.lower()
    if ext == ".ico" and stem == "bing":
        from PIL import Image

        im = Image.open(fpath).convert("RGBA")
        im.resize((64, 64), Image.LANCZOS).save("/tmp/bing64.png")
        add("bing.png", open("/tmp/bing64.png", "rb").read(), ".png")
    elif ext in MIME:
        with open(fpath, "rb") as f:
            add(fname, f.read(), ext)

lines = [
    "// AUTO-GENERATED by scripts/gen_site_icons.py — do not edit by hand.",
    "// Real brand icons for new-tab tiles + search engine badge.",
    "export const SITE_ICONS: Record<string, string> = {",
]
for key in sorted(entries):
    lines.append(f"  {key!r}: {entries[key]!r},")
lines.append("};")
lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))

total = sum(len(v) for v in entries.values())
print(f"wrote {OUT}: {len(entries)} icons, {total / 1024:.1f} KB")
for key in sorted(entries):
    print(" ", key, f"{len(entries[key]) / 1024:.1f} KB")
